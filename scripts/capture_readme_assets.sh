#!/usr/bin/env bash
# =============================================================================
# scripts/capture_readme_assets.sh — regenerate the README screenshots
# =============================================================================
# GitHub #381 (PR 1 of #356); ADR 2026-10-13 "README Assets Are Generated From
# Synthetic Data, Never Hand-Edited"; Docs/README_ASSETS.md.
#
# 1. Renders the soos-gui screens headlessly from synthetic data (placeholder
#    face, mock models, user alice) through the snapshot test in update mode and
#    writes Docs/assets/screenshots/gui-*.png. Hardware-free: no camera, no
#    daemon, no display server, no GPU, no network.
# 2. With --web, also runs scripts/capture_readme_web.sh (needs an installed
#    Chrome or Chromium; optional, never a CI step).
# 3. Rewrites Docs/assets/MANIFEST.toml (path, generator, SHA-256) from the
#    files on disk; the soos-invariants readme_assets_contract verifies it.
#
# Usage: scripts/capture_readme_assets.sh [--web]
# =============================================================================

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ASSETS="$ROOT/Docs/assets"
MANIFEST="$ASSETS/MANIFEST.toml"
GUI_GENERATOR="soos-gui readme_snapshots"
WEB_GENERATOR="scripts/capture_readme_web.sh"

with_web=0
for arg in "$@"; do
    case "$arg" in
        --web) with_web=1 ;;
        -h | --help)
            sed -n '2,18p' "${BASH_SOURCE[0]}"
            exit 0
            ;;
        *)
            echo "capture_readme_assets.sh: unknown argument $arg" >&2
            exit 2
            ;;
    esac
done

if [[ -n "${CI:-}" ]]; then
    echo "capture_readme_assets.sh: refusing to regenerate assets in CI" >&2
    exit 2
fi

cd "$ROOT"
echo "==> Rendering the soos-gui README screens (synthetic data only)"
SOOS_UPDATE_README_ASSETS=1 cargo test --locked -p soos-gui --features readme-capture \
    --test readme_snapshots -- --exact test_rac_capture_scenes_match_committed_assets

if [[ "$with_web" -eq 1 ]]; then
    echo "==> Capturing the phone companion web app (optional)"
    "$ROOT/scripts/capture_readme_web.sh"
fi

echo "==> Rewriting $MANIFEST"
tmp="$(mktemp "$ASSETS/.MANIFEST.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
    echo "# Generated by scripts/capture_readme_assets.sh. Never edit by hand."
    echo "# Verified by soos-invariants readme_assets_contract (ADR 2026-10-13)."
    while IFS= read -r -d '' file; do
        rel="${file#"$ASSETS"/}"
        case "$rel" in
            screenshots/gui-*.png) generator="$GUI_GENERATOR" ;;
            screenshots/web-*.png) generator="$WEB_GENERATOR" ;;
            *)
                echo "capture_readme_assets.sh: $rel has no known generator" >&2
                exit 1
                ;;
        esac
        sha="$(sha256sum "$file" | cut -d' ' -f1)"
        printf '\n[[asset]]\npath = "%s"\ngenerator = "%s"\nsha256 = "%s"\nsource = "synthetic"\n' \
            "$rel" "$generator" "$sha"
    done < <(find "$ASSETS" -type f ! -name 'MANIFEST.toml' ! -name '.MANIFEST.*' -print0 | LC_ALL=C sort -z)
} > "$tmp"
mv "$tmp" "$MANIFEST"
trap - EXIT
echo "==> Done: $(grep -c '^\[\[asset\]\]' "$MANIFEST") assets listed"
