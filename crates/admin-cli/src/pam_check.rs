//! Read-only check of the `auth` stacks of `/etc/pam.d` for a soos rule that ends the stack
//! (`[success=done]` or `sufficient`) before an enforcing rule that the password path still
//! runs: a second factor or gate placed after a shared `include` (security review 2026-11-10,
//! finding `PSTK-01`, GitHub #574; ADR 2026-11-20 in `AI/DECISIONS.md`).
//!
//! The analysis flattens one auth stack (`include` / `@include` spliced inline, `substack`
//! as a nested frame, every other phase skipped) and runs it twice under the same outcome of
//! every conditional rule: scenario A, where the primary soos rules return `PAM_SUCCESS` (a
//! face match), and scenario B, where they return `PAM_IGNORE` and the credential modules
//! met after them return `PAM_SUCCESS` (the correct-password path). A rule visited in B and
//! not in A whose control can fail the stack is a rule the face match skips. Nothing here
//! writes to disk.

use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};

use crate::error::AdminCliError;
use crate::pam_stack::{
    read_bounded_utf8, PamLine, ReadError, CREDENTIAL_MODULES, MAX_PAM_INCLUDE_DEPTH,
    MAX_PAM_STACK_READS,
};

/// Maximum number of service files examined by one `soos-admin pam check`.
pub const MAX_PAM_CHECK_SERVICES: usize = 256;

/// Maximum number of auth rules in one flattened stack; a larger stack is not analysed.
pub const MAX_PAM_CHECK_RULES: usize = 1024;

/// Maximum number of conditional rules (branch points) explored in one stack; every
/// assignment of their outcomes is simulated (at most `2^8` = 256 runs per scenario).
pub const MAX_PAM_CHECK_BRANCHES: usize = 8;

/// Debian stacks generated by `pam-auth-update` for one management group other than `auth`.
/// An `@include` of one of them is skipped when the file is missing; a present file is
/// analysed like any other stack.
const DEBIAN_NON_AUTH_STACKS: &[&str] = &[
    "common-account",
    "common-password",
    "common-session",
    "common-session-noninteractive",
];

/// Modules whose skipping by a face match is never reported, besides the credential modules
/// the face match replaces: soos itself and modules that cannot reject a login.
const EXEMPT_MODULES: &[&str] = &[
    "pam_soos.so",
    "pam_permit.so",
    "pam_env.so",
    "pam_faildelay.so",
];

/// Failure fallback of a shared stack (`auth required pam_deny.so`). In the anchor's own
/// delegated stack of `gdm enable` it is not reported: the simulation lets every credential
/// module succeed, so a fallback it still reaches would deny the correct password too (the
/// shared stack then denies every service). The face path never needs that fallback, and
/// such a rule in the edited file itself is still reported.
const ANCHOR_FALLBACK_MODULE: &str = "pam_deny.so";

/// Suffix of the pristine copies kept by `soos-admin gdm enable` (never a service).
const BACKUP_SUFFIX: &str = ".soos-backup";

/// An enforcing auth rule that a face match skips although the password path runs it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SkippedRule {
    /// Name of the stack file holding the rule.
    pub stack: String,
    /// 1-based line number of the rule in that file.
    pub line: usize,
    /// `'<module>' (control '<control>')`.
    pub rule: String,
}

/// A service whose soos rule ends the stack before at least one [`SkippedRule`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ServiceFinding {
    /// Service file name.
    pub service: String,
    /// Stack file holding the soos rule that ends the stack.
    pub soos_stack: String,
    /// 1-based line number of that soos rule.
    pub soos_line: usize,
    /// Rules the face match skips.
    pub skipped: Vec<SkippedRule>,
}

/// A service whose stack could not be analysed (never reported as clean).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct UnanalysedService {
    /// Service file name.
    pub service: String,
    /// Operator-facing reason.
    pub reason: String,
}

/// Result of [`check_pam_services`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct PamCheckReport {
    /// Inspected PAM directory.
    pub pam_dir: PathBuf,
    /// Number of service files examined.
    pub services_checked: usize,
    /// Services where a face match skips an enforcing rule.
    pub findings: Vec<ServiceFinding>,
    /// Services that could not be analysed.
    pub unanalysed: Vec<UnanalysedService>,
}

impl PamCheckReport {
    /// `0` clean, `1` at least one finding, `2` no finding but at least one unanalysed service.
    #[must_use]
    pub fn exit_code(&self) -> i32 {
        if !self.findings.is_empty() {
            1
        } else if !self.unanalysed.is_empty() {
            2
        } else {
            0
        }
    }

    /// Human-readable report.
    #[must_use]
    pub fn format_table(&self) -> String {
        let mut out = String::from("PAM Stack Check (soos rules that end the auth stack):\n");
        out.push_str(&format!(
            "  PAM Directory:     {}\n  Services Checked:  {}\n",
            printable(&self.pam_dir.display().to_string()),
            self.services_checked
        ));
        if self.findings.is_empty() && self.unanalysed.is_empty() {
            out.push_str(
                "  Result:            no enforcing auth rule is skipped by a face match\n",
            );
            return out;
        }
        for finding in &self.findings {
            out.push_str(&format!(
                "  [SKIP] {}: the soos rule at {}:{} ends the stack before:\n",
                finding.service, finding.soos_stack, finding.soos_line
            ));
            for rule in &finding.skipped {
                out.push_str(&format!(
                    "           {}:{} {}\n",
                    rule.stack, rule.line, rule.rule
                ));
            }
        }
        for service in &self.unanalysed {
            out.push_str(&format!(
                "  [UNKNOWN] {}: {}\n",
                service.service, service.reason
            ));
        }
        if !self.findings.is_empty() {
            out.push_str(
                "  A face match skips these rules although a correct password runs them; move \
                 them before the include or see Docs/DISTRIBUTION_DEPLOYMENT.md section 2.\n",
            );
        }
        out
    }

    /// Machine-readable report.
    #[must_use]
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).unwrap_or_else(|_| "{}".to_string())
    }
}

/// Replaces control characters (terminal escapes) of an operator-supplied text.
fn printable(text: &str) -> String {
    text.chars()
        .map(|c| if c.is_control() { '?' } else { c })
        .collect()
}

/// True for a name usable as a file name inside the PAM directory.
fn valid_name(name: &str) -> bool {
    !name.is_empty()
        && !name.starts_with('.')
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
}

/// One flattened auth rule.
#[derive(Debug, Clone)]
struct Rule {
    id: usize,
    stack: String,
    line: usize,
    control: String,
    module: String,
    /// Module arguments, verbatim.
    args: Vec<String>,
    soos_primary: bool,
    /// Rule of the anchor's own delegated stack (`gdm enable` analysis only).
    in_anchor: bool,
}

/// One node of a flattened auth chain.
#[derive(Debug, Clone)]
enum Node {
    Rule(Rule),
    /// `substack`: `done`/`die` inside end only this frame.
    Substack(Vec<Node>),
    /// Delegated stack that could not be analysed (anchor of `gdm enable` only).
    Opaque,
}

/// Action of a control for one return value.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Act {
    Continue,
    Terminate,
    Jump(usize),
    Unknown,
}

/// Return values the simulation uses.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Ret {
    Success,
    Ignore,
    Failure,
}

/// True for a non-empty decimal number.
fn is_digits(value: &str) -> bool {
    !value.is_empty() && value.bytes().all(|b| b.is_ascii_digit())
}

/// Action of `control` for `ret` (pam.conf(5)): keyword controls, or the value of the matching
/// key of a bracketed control, else `default`, else `bad`.
fn action(control: &str, ret: Ret) -> Act {
    let Some(inside) = control.strip_prefix('[').and_then(|c| c.strip_suffix(']')) else {
        return match control.to_ascii_lowercase().as_str() {
            "required" | "optional" => Act::Continue,
            "requisite" => match ret {
                Ret::Failure => Act::Terminate,
                Ret::Success | Ret::Ignore => Act::Continue,
            },
            "sufficient" => match ret {
                Ret::Success => Act::Terminate,
                Ret::Ignore | Ret::Failure => Act::Continue,
            },
            _ => Act::Unknown,
        };
    };
    let key = match ret {
        Ret::Success => "success",
        Ret::Ignore => "ignore",
        Ret::Failure => "auth_err",
    };
    let mut specific = None;
    let mut default = None;
    for token in inside.split_whitespace() {
        let Some((k, v)) = token.split_once('=') else {
            return Act::Unknown;
        };
        if k.eq_ignore_ascii_case(key) {
            specific = Some(v);
        } else if k.eq_ignore_ascii_case("default") {
            default = Some(v);
        }
    }
    let value = specific.or(default).unwrap_or("bad").to_ascii_lowercase();
    match value.as_str() {
        "ignore" | "ok" | "bad" | "reset" => Act::Continue,
        "done" | "die" => Act::Terminate,
        digits if is_digits(digits) => digits.parse::<usize>().map_or(Act::Unknown, Act::Jump),
        _ => Act::Unknown,
    }
}

/// True when `control` can make the stack fail (fail closed on anything unknown): `required`,
/// `requisite` or an unknown keyword; a bracket without `default=`, or one whose `success` key
/// is not `ignore`/`ok`/`done`/`N`, or whose other keys are not `ignore`/`N`.
fn may_fail_stack(control: &str) -> bool {
    let Some(inside) = control.strip_prefix('[').and_then(|c| c.strip_suffix(']')) else {
        return !(control.eq_ignore_ascii_case("optional")
            || control.eq_ignore_ascii_case("sufficient"));
    };
    let mut has_default = false;
    for token in inside.split_whitespace() {
        let Some((key, value)) = token.split_once('=') else {
            return true;
        };
        if key.eq_ignore_ascii_case("default") {
            has_default = true;
        }
        let harmless = if key.eq_ignore_ascii_case("success") {
            ["ignore", "ok", "done"]
                .iter()
                .any(|v| value.eq_ignore_ascii_case(v))
                || is_digits(value)
        } else {
            value.eq_ignore_ascii_case("ignore") || is_digits(value)
        };
        if !harmless {
            return true;
        }
    }
    !has_default
}

impl Rule {
    fn describe(&self) -> String {
        format!("'{}' (control '{}')", self.module, self.control)
    }

    fn is_credential(&self) -> bool {
        CREDENTIAL_MODULES.contains(&self.module.as_str())
    }

    /// Enforcing and not exempt: its skipping by a face match is reported.
    fn is_reportable(&self) -> bool {
        !self.is_credential()
            && !EXEMPT_MODULES.contains(&self.module.as_str())
            && may_fail_stack(&self.control)
    }

    /// Conditional rule explored on both branches: a bracketed or `sufficient` control whose
    /// success and failure actions differ (soos and credential rules excepted).
    fn is_branch_point(&self) -> bool {
        !self.soos_primary
            && !self.is_credential()
            && (self.control.starts_with('[') || self.control.eq_ignore_ascii_case("sufficient"))
            && action(&self.control, Ret::Success) != action(&self.control, Ret::Failure)
    }

    fn has_arg(&self, arg: &str) -> bool {
        self.args.iter().any(|a| a == arg)
    }

    /// A plain `required` or `requisite` control.
    fn is_plain_enforcing(&self) -> bool {
        self.control.eq_ignore_ascii_case("required")
            || self.control.eq_ignore_ascii_case("requisite")
    }

    /// `pam_faillock.so preauth` with a plain enforcing control: the tally check.
    fn is_faillock_preauth_gate(&self) -> bool {
        self.module == "pam_faillock.so" && self.has_arg("preauth") && self.is_plain_enforcing()
    }

    /// `pam_faillock.so authsucc`: the tally check repeated after a successful credential,
    /// then the reset of the failure tally.
    fn is_faillock_authsucc(&self) -> bool {
        self.module == "pam_faillock.so" && self.has_arg("authsucc")
    }

    /// True when skipping this rule is known to be equivalent for the face path because of a
    /// rule in `ran` (rules that run before the face rule on the face path):
    ///
    /// - an identical copy (same module, plain enforcing control, same arguments), such as a
    ///   gate that `gdm enable` copied in front of its managed rule;
    /// - for `pam_faillock.so authsucc`, an enforcing `pam_faillock.so preauth` gate, which
    ///   already ran the same tally check (only the reset of the tally is skipped, which
    ///   leaves the face path stricter, never weaker).
    fn covered_by(&self, ran: &[&Rule]) -> bool {
        ran.iter().any(|r| {
            (self.is_plain_enforcing()
                && r.module == self.module
                && r.control.eq_ignore_ascii_case(&self.control)
                && r.args == self.args)
                || (self.is_faillock_authsucc() && r.is_faillock_preauth_gate())
        })
    }

    fn skipped(&self) -> SkippedRule {
        SkippedRule {
            stack: self.stack.clone(),
            line: self.line,
            rule: self.describe(),
        }
    }
}

/// Bounded flattener of auth stacks.
struct Flattener<'d> {
    dir: &'d Path,
    reads_left: usize,
    rules: usize,
}

impl<'d> Flattener<'d> {
    fn new(dir: &'d Path) -> Self {
        Self {
            dir,
            reads_left: MAX_PAM_STACK_READS,
            rules: 0,
        }
    }

    /// Reads and flattens the stack file `name` (validated as a name inside the directory).
    /// `at_include`: reached through `@include` (a missing Debian non-auth stack is skipped).
    fn flatten_stack(
        &mut self,
        name: &str,
        depth: usize,
        in_anchor: bool,
        at_include: bool,
        out: &mut Vec<Node>,
    ) -> Result<(), String> {
        if depth > MAX_PAM_INCLUDE_DEPTH {
            return Err(format!(
                "include chain deeper than {MAX_PAM_INCLUDE_DEPTH} levels at '{}'",
                printable(name)
            ));
        }
        if !valid_name(name) {
            return Err(format!(
                "cannot resolve the included stack '{}' inside the PAM directory",
                printable(name)
            ));
        }
        self.reads_left = self.reads_left.checked_sub(1).ok_or_else(|| {
            format!("more than {MAX_PAM_STACK_READS} stack files opened at '{name}'")
        })?;
        let content = match read_bounded_utf8(&self.dir.join(name)) {
            Ok(content) => content,
            Err(ReadError::NotFound) if at_include && DEBIAN_NON_AUTH_STACKS.contains(&name) => {
                return Ok(())
            }
            Err(ReadError::NotFound) => {
                return Err(format!(
                    "the included stack '{name}' was not found inside the PAM directory \
                     (vendor directories such as /usr/lib/pam.d are not searched)"
                ))
            }
            Err(ReadError::Other(msg)) => return Err(msg),
        };
        let lines: Vec<&str> = content.lines().collect();
        self.flatten_lines(name, &lines, 0, depth, in_anchor, out)
    }

    /// Flattens `lines` of stack `stack`; `first_line` is the 0-based index of the first one.
    fn flatten_lines(
        &mut self,
        stack: &str,
        lines: &[&str],
        first_line: usize,
        depth: usize,
        in_anchor: bool,
        out: &mut Vec<Node>,
    ) -> Result<(), String> {
        for (offset, raw) in lines.iter().enumerate() {
            if raw.trim_end().ends_with('\\') {
                return Err(format!("'{stack}' uses line continuations"));
            }
            let Some(line) = PamLine::parse(raw) else {
                continue;
            };
            if !line.is_auth() {
                continue;
            }
            let number = first_line.saturating_add(offset).saturating_add(1);
            self.push_line(stack, number, &line, depth, in_anchor, out)?;
        }
        Ok(())
    }

    /// Appends one auth line (rule or delegation) to `out`.
    fn push_line(
        &mut self,
        stack: &str,
        number: usize,
        line: &PamLine<'_>,
        depth: usize,
        in_anchor: bool,
        out: &mut Vec<Node>,
    ) -> Result<(), String> {
        let next = depth.saturating_add(1);
        match line {
            PamLine::AtInclude(target) => self.flatten_stack(target, next, in_anchor, true, out),
            PamLine::Rule {
                control, module, ..
            } if line.delegation().is_some() => {
                if control.eq_ignore_ascii_case("substack") {
                    let mut inner = Vec::new();
                    self.flatten_stack(module, next, in_anchor, false, &mut inner)?;
                    out.push(Node::Substack(inner));
                    Ok(())
                } else {
                    self.flatten_stack(module, next, in_anchor, false, out)
                }
            }
            PamLine::Rule { control, args, .. } => {
                self.rules = self.rules.saturating_add(1);
                if self.rules > MAX_PAM_CHECK_RULES {
                    return Err(format!(
                        "more than {MAX_PAM_CHECK_RULES} auth rules in the flattened stack"
                    ));
                }
                let module = line.module_name().unwrap_or_default().to_string();
                let soos_primary =
                    module == "pam_soos.so" && !args.iter().any(|arg| arg.starts_with("event="));
                out.push(Node::Rule(Rule {
                    id: self.rules,
                    stack: stack.to_string(),
                    line: number,
                    control: (*control).to_string(),
                    module,
                    args: args.iter().map(|arg| (*arg).to_string()).collect(),
                    soos_primary,
                    in_anchor,
                }));
                Ok(())
            }
        }
    }
}

/// Visits every rule of `nodes` (recursively, in order).
fn for_each_rule<'n>(nodes: &'n [Node], f: &mut dyn FnMut(&'n Rule)) {
    for node in nodes {
        match node {
            Node::Rule(rule) => f(rule),
            Node::Substack(inner) => for_each_rule(inner, f),
            Node::Opaque => {}
        }
    }
}

/// One simulation run.
struct Run<'a> {
    /// Ids of the branch points that succeed in this assignment.
    succeeding: &'a [usize],
    /// Return value of the primary soos rules.
    soos: Ret,
    /// A primary soos rule was met: credential modules return `PAM_SUCCESS` from then on (the
    /// password path); before it they are alternatives that do not apply (`PAM_IGNORE`).
    soos_seen: bool,
    visited: Vec<usize>,
    unknown: bool,
    /// First primary soos rule that ended a frame, `(stack, line)`.
    soos_end: Option<(String, usize)>,
}

impl<'a> Run<'a> {
    fn new(succeeding: &'a [usize], soos: Ret, soos_seen: bool) -> Self {
        Self {
            succeeding,
            soos,
            soos_seen,
            visited: Vec::new(),
            unknown: false,
            soos_end: None,
        }
    }

    fn ret_of(&mut self, rule: &Rule) -> Ret {
        if rule.soos_primary {
            self.soos_seen = true;
            self.soos
        } else if rule.is_credential() {
            if self.soos_seen {
                Ret::Success
            } else {
                Ret::Ignore
            }
        } else if rule.is_branch_point() && !self.succeeding.contains(&rule.id) {
            Ret::Failure
        } else {
            Ret::Success
        }
    }

    /// Runs one frame until its end or a `done`/`die` action.
    fn frame(&mut self, nodes: &[Node]) {
        let mut index = 0_usize;
        while let Some(node) = nodes.get(index) {
            let step = match node {
                Node::Opaque => Act::Unknown,
                Node::Substack(inner) => {
                    self.frame(inner);
                    Act::Continue
                }
                Node::Rule(rule) => {
                    self.visited.push(rule.id);
                    let ret = self.ret_of(rule);
                    let act = action(&rule.control, ret);
                    if rule.soos_primary && act == Act::Terminate && self.soos_end.is_none() {
                        self.soos_end = Some((rule.stack.clone(), rule.line));
                    }
                    act
                }
            };
            match step {
                Act::Continue => index = index.saturating_add(1),
                Act::Terminate => return,
                Act::Unknown => {
                    self.unknown = true;
                    index = index.saturating_add(1);
                }
                Act::Jump(n) => {
                    let target = index.checked_add(n).and_then(|t| t.checked_add(1));
                    let span = target.and_then(|t| nodes.get(index.saturating_add(1)..t));
                    match (target, span) {
                        (Some(target), Some(span))
                            if span.iter().all(|n| matches!(n, Node::Rule(_))) =>
                        {
                            index = target;
                        }
                        // A jump over a substack or past the end of the frame cannot be
                        // followed exactly.
                        _ => {
                            self.unknown = true;
                            return;
                        }
                    }
                }
            }
        }
    }
}

/// Every assignment of the branch points of `nodes`, or `None` when there are too many.
fn assignments(nodes: &[Node]) -> Option<Vec<Vec<usize>>> {
    let mut points = Vec::new();
    for_each_rule(nodes, &mut |rule| {
        if rule.is_branch_point() {
            points.push(rule.id);
        }
    });
    if points.len() > MAX_PAM_CHECK_BRANCHES {
        return None;
    }
    let count = 1_usize.checked_shl(u32::try_from(points.len()).ok()?)?;
    Some(
        (0..count)
            .map(|mask| {
                points
                    .iter()
                    .enumerate()
                    .filter(|(bit, _)| {
                        u32::try_from(*bit)
                            .ok()
                            .and_then(|b| mask.checked_shr(b))
                            .is_some_and(|m| m & 1 == 1)
                    })
                    .map(|(_, id)| *id)
                    .collect()
            })
            .collect(),
    )
}

/// `((soos stack, soos line), skipped rules)` of [`compare`].
type Comparison<'n> = ((String, usize), Vec<&'n Rule>);

/// The soos rule that ends the stack in scenario A and the reportable rules visited in B but
/// not in A, over every assignment; `Ok(None)` when no soos rule ends the stack.
///
/// # Errors
///
/// Too many branch points, or a run that cannot be followed exactly.
fn compare(nodes: &[Node]) -> Result<Option<Comparison<'_>>, String> {
    let all = assignments(nodes).ok_or_else(|| {
        format!("more than {MAX_PAM_CHECK_BRANCHES} conditional auth rules to explore")
    })?;
    let mut rules: Vec<&Rule> = Vec::new();
    for_each_rule(nodes, &mut |rule| rules.push(rule));
    let mut soos_end = None;
    let mut skipped: Vec<&Rule> = Vec::new();
    for succeeding in &all {
        let mut face = Run::new(succeeding, Ret::Success, false);
        face.frame(nodes);
        let mut password = Run::new(succeeding, Ret::Ignore, false);
        password.frame(nodes);
        if face.unknown || password.unknown {
            return Err(
                "a control, jump or delegated stack could not be followed exactly".to_string(),
            );
        }
        let Some(end) = face.soos_end else {
            continue;
        };
        // Rules the face path ran before its soos rule ended the stack (copied gates).
        let ran: Vec<&Rule> = rules
            .iter()
            .copied()
            .filter(|rule| face.visited.contains(&rule.id))
            .collect();
        for rule in &rules {
            if password.visited.contains(&rule.id)
                && !face.visited.contains(&rule.id)
                && rule.is_reportable()
                && !rule.covered_by(&ran)
                && !skipped.iter().any(|r| r.id == rule.id)
            {
                skipped.push(rule);
                if soos_end.is_none() {
                    soos_end = Some(end.clone());
                }
            }
        }
    }
    Ok(soos_end.map(|end| (end, skipped)))
}

/// True when `nodes` contain a primary soos rule that ends its frame on success.
fn has_ending_soos_rule(nodes: &[Node]) -> bool {
    let mut found = false;
    for_each_rule(nodes, &mut |rule| {
        if rule.soos_primary && action(&rule.control, Ret::Success) == Act::Terminate {
            found = true;
        }
    });
    found
}

/// Analyses one service file.
fn check_service(dir: &Path, service: &str) -> Result<Option<ServiceFinding>, String> {
    let mut flattener = Flattener::new(dir);
    let mut nodes = Vec::new();
    flattener.flatten_stack(service, 0, false, false, &mut nodes)?;
    if !has_ending_soos_rule(&nodes) {
        return Ok(None);
    }
    Ok(
        compare(&nodes)?.and_then(|((soos_stack, soos_line), skipped)| {
            (!skipped.is_empty()).then(|| ServiceFinding {
                service: service.to_string(),
                soos_stack,
                soos_line,
                skipped: skipped.iter().map(|r| r.skipped()).collect(),
            })
        }),
    )
}

/// Checks `services` of `pam_dir` (every service file when empty: regular files, symlinks
/// followed, with a `[A-Za-z0-9._-]` name not starting with `.` and not ending with
/// `.soos-backup`, sorted, at most [`MAX_PAM_CHECK_SERVICES`]).
///
/// # Errors
///
/// An unreadable directory, an invalid service name, or more than
/// [`MAX_PAM_CHECK_SERVICES`] services. A service that cannot be analysed is reported in
/// [`PamCheckReport::unanalysed`], never as an error.
pub fn check_pam_services(
    pam_dir: &Path,
    services: &[String],
) -> Result<PamCheckReport, AdminCliError> {
    let names = if services.is_empty() {
        list_services(pam_dir)?
    } else {
        if let Some(bad) = services.iter().find(|s| !valid_name(s)) {
            return Err(AdminCliError::GdmConfig(format!(
                "invalid PAM service name '{}': expected a file name made of [A-Za-z0-9._-]",
                printable(bad)
            )));
        }
        if services.len() > MAX_PAM_CHECK_SERVICES {
            return Err(AdminCliError::GdmConfig(format!(
                "more than {MAX_PAM_CHECK_SERVICES} services requested"
            )));
        }
        services.to_vec()
    };
    let mut report = PamCheckReport {
        pam_dir: pam_dir.to_path_buf(),
        services_checked: names.len(),
        findings: Vec::new(),
        unanalysed: Vec::new(),
    };
    for service in names {
        match check_service(pam_dir, &service) {
            Ok(Some(finding)) => report.findings.push(finding),
            Ok(None) => {}
            Err(reason) => report
                .unanalysed
                .push(UnanalysedService { service, reason }),
        }
    }
    Ok(report)
}

/// Service files of `pam_dir`, sorted.
fn list_services(pam_dir: &Path) -> Result<Vec<String>, AdminCliError> {
    let entries = fs::read_dir(pam_dir).map_err(|e| {
        AdminCliError::GdmConfig(format!(
            "cannot read the PAM directory '{}': {e}",
            printable(&pam_dir.display().to_string())
        ))
    })?;
    let mut names = Vec::new();
    for entry in entries.flatten() {
        let Ok(name) = entry.file_name().into_string() else {
            continue;
        };
        if !valid_name(&name) || name.ends_with(BACKUP_SUFFIX) {
            continue;
        }
        if !fs::metadata(entry.path()).is_ok_and(|m| m.is_file()) {
            continue;
        }
        if names.len() >= MAX_PAM_CHECK_SERVICES {
            return Err(AdminCliError::GdmConfig(format!(
                "the PAM directory holds more than {MAX_PAM_CHECK_SERVICES} service files; \
                 name the services to check"
            )));
        }
        names.push(name);
    }
    names.sort();
    Ok(names)
}

/// `gdm enable` (GitHub #574): the first enforcing auth rule that the managed
/// `[success=done]` rule, inserted at the top level right before `lines[anchor_index]` of the
/// edited file `edited`, would skip although the password path still runs it. Rules up to the
/// first credential module are the gates `gdm enable` already copies or refuses. Every rule
/// after it counts, in the anchor's own delegated stack too (a second factor after the
/// credential module of a shared `common-auth`), unless a rule that runs before the managed
/// rule covers it (`Rule::covered_by`: an identical copy, or `pam_faillock.so authsucc` after
/// a `pam_faillock.so preauth` gate) or it is the `pam_deny.so` failure fallback of the
/// anchor's own stack ([`ANCHOR_FALLBACK_MODULE`]). An anchor stack that cannot be analysed is
/// followed as unknown.
///
/// When the password path cannot be followed exactly, every enforcing rule after the anchor
/// counts (fail closed: reachability assumed).
///
/// # Errors
///
/// The tail after the anchor cannot be analysed (missing or invalid include target, depth,
/// read budget, rule bound, continuation line): the caller refuses.
pub(crate) fn gdm_tail_skips(
    dir: &Path,
    edited: &str,
    lines: &[&str],
    anchor_index: usize,
) -> Result<Option<SkippedRule>, String> {
    let mut flattener = Flattener::new(dir);
    let mut nodes = Vec::new();
    let anchor_number = anchor_index.saturating_add(1);
    let mut opaque_anchor = false;
    if let Some(anchor) = lines.get(anchor_index).and_then(|raw| PamLine::parse(raw)) {
        let mut anchor_nodes = Vec::new();
        match flattener.push_line(edited, anchor_number, &anchor, 0, true, &mut anchor_nodes) {
            Ok(()) => nodes.append(&mut anchor_nodes),
            Err(_) => {
                opaque_anchor = true;
                nodes.push(Node::Opaque);
            }
        }
    }
    let tail = lines
        .get(anchor_index.saturating_add(1)..)
        .unwrap_or_default();
    flattener.flatten_lines(edited, tail, anchor_number, 0, false, &mut nodes)?;

    // The managed rule itself is the soos rule: credential modules met afterwards are the
    // password path (`soos_seen` from the start).
    let reached = assignments(&nodes).and_then(|all| {
        let mut reached: Vec<usize> = Vec::new();
        for succeeding in &all {
            let mut password = Run::new(succeeding, Ret::Ignore, true);
            password.frame(&nodes);
            if password.unknown {
                return None;
            }
            reached.extend(password.visited);
        }
        Some(reached)
    });
    // Every rule up to the first credential module (in evaluation order) was classified by
    // the delegated-stack scan of `gdm enable`: copied in front of the managed rule as a gate,
    // or refused. Only the rules after it can be skipped. An anchor stack that cannot be
    // analysed holds that credential module (the scan of `gdm enable` reached it): every tail
    // rule counts (fail closed).
    let mut rules: Vec<&Rule> = Vec::new();
    let mut gates: Vec<&Rule> = Vec::new();
    let mut credential_met = opaque_anchor;
    for_each_rule(&nodes, &mut |rule| {
        if credential_met {
            rules.push(rule);
        } else {
            gates.push(rule);
        }
        credential_met |= rule.is_credential();
    });
    // The rules of the edited file before the anchor run before the managed rule too. They
    // are plain rules (the anchor is the first delegation or credential module); when they
    // cannot be flattened, none of them covers anything (fail closed).
    let mut head = Vec::new();
    let head_lines = lines.get(..anchor_index).unwrap_or_default();
    if Flattener::new(dir)
        .flatten_lines(edited, head_lines, 0, 0, false, &mut head)
        .is_err()
    {
        head.clear();
    }
    for_each_rule(&head, &mut |rule| gates.push(rule));
    let first = rules.iter().find(|rule| {
        rule.is_reportable()
            && !(rule.in_anchor && rule.module == ANCHOR_FALLBACK_MODULE)
            && !rule.covered_by(&gates)
            && reached.as_ref().is_none_or(|ids| ids.contains(&rule.id))
    });
    Ok(first.map(|rule| rule.skipped()))
}

#[cfg(test)]
mod tests {
    #![allow(
        clippy::unwrap_used,
        clippy::expect_used,
        reason = "unit tests use direct assertions"
    )]
    use super::*;

    #[test]
    fn test_action_follows_pam_conf_semantics() {
        assert_eq!(action("required", Ret::Success), Act::Continue);
        assert_eq!(action("Sufficient", Ret::Success), Act::Terminate);
        assert_eq!(action("sufficient", Ret::Ignore), Act::Continue);
        assert_eq!(action("requisite", Ret::Failure), Act::Terminate);
        assert_eq!(
            action("[success=done default=ignore]", Ret::Success),
            Act::Terminate
        );
        assert_eq!(
            action("[success=done default=ignore]", Ret::Ignore),
            Act::Continue
        );
        assert_eq!(
            action("[success=2 default=ignore]", Ret::Success),
            Act::Jump(2)
        );
        assert_eq!(action("[default=die]", Ret::Success), Act::Terminate);
        assert_eq!(action("[success=ok]", Ret::Failure), Act::Continue);
        assert_eq!(
            action("[success=weird default=ignore]", Ret::Success),
            Act::Unknown
        );
        assert_eq!(action("frobnicate", Ret::Success), Act::Unknown);
        assert_eq!(action("[success]", Ret::Success), Act::Unknown);
    }

    #[test]
    fn test_may_fail_stack_classifies_controls() {
        for enforcing in [
            "required",
            "REQUISITE",
            "unknown",
            "[success=ok]",
            "[success=ok default=bad]",
            "[default=die]",
            "[success=ok default=ignore auth_err=bad]",
            "[success=ignore default=ok]",
            "[success=ok default=reset]",
            "[success=bad default=ignore]",
            "[success default=ignore]",
        ] {
            assert!(may_fail_stack(enforcing), "{enforcing}");
        }
        for harmless in [
            "optional",
            "sufficient",
            "[success=ok default=ignore]",
            "[success=done default=ignore]",
            "[success=1 default=ignore]",
            "[success=ok ignore=ignore default=1]",
        ] {
            assert!(!may_fail_stack(harmless), "{harmless}");
        }
    }

    #[test]
    fn test_assignments_are_bounded() {
        let rule = |id: usize| {
            Node::Rule(Rule {
                id,
                stack: "s".into(),
                line: id,
                control: "[success=1 default=ignore]".into(),
                module: "pam_succeed_if.so".into(),
                soos_primary: false,
                args: Vec::new(),
                in_anchor: false,
            })
        };
        let eight: Vec<Node> = (1..=8).map(rule).collect();
        assert_eq!(assignments(&eight).map(|a| a.len()), Some(256));
        let nine: Vec<Node> = (1..=9).map(rule).collect();
        assert!(assignments(&nine).is_none());
    }
}
