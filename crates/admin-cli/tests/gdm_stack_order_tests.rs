//! delegates to as shipped by Ubuntu 24.04 (`gdm3`), Fedora 40 (`gdm` +
//! `authselect local with-faillock`) and Arch Linux (`gdm` + `pambase`).
//! The invariant under test: a facial success can never skip a lockout, nologin,
//! shell or user-filter gate (`pam_faillock.so preauth`, `pam_nologin.so`,
//! `pam_shells.so`, `pam_succeed_if.so`) that the original stack runs before the
