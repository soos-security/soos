struct Fixture {
    _dir: tempfile::TempDir,
    pam_dir: PathBuf,
    pam_file: PathBuf,
    disable_file: PathBuf,
}

fn fixture(gdm_password: &str, shared: &[(&str, &str)]) -> Fixture {
    let dir = tempdir().unwrap();
    let pam_dir = dir.path().join("pam.d");
    fs::create_dir(&pam_dir).unwrap();
    for (name, content) in shared {
        fs::write(pam_dir.join(name), content).unwrap();
    }
    let pam_file = pam_dir.join("gdm-password");
    fs::write(&pam_file, gdm_password).unwrap();
    let disable_file = dir.path().join("soos").join("gdm.disable");
    Fixture {
        _dir: dir,
        pam_dir,
        pam_file,
        disable_file,
    }
}

fn enable(f: &Fixture) -> String {
    configure_gdm(&GdmAction::Enable, &f.pam_file, &f.disable_file).expect("enable must succeed");
    fs::read_to_string(&f.pam_file).unwrap()
}

/// Returns `(type, control, module, args)` for an active PAM rule line.
fn parse_rule(line: &str) -> Option<(String, String, String, String)> {
    let line = line.trim();
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    if let Some(rest) = line.strip_prefix("@include") {
        return Some((
            "@include".into(),
            "include".into(),
            rest.trim().into(),
            String::new(),
        ));
    }
    let (kind, rest) = line.split_once(char::is_whitespace)?;
    let rest = rest.trim_start();
    let (control, rest) = if rest.starts_with('[') {
        let end = rest.find(']')?;
        (rest[..=end].to_string(), rest[end + 1..].trim_start())
    } else {
        let (c, r) = rest.split_once(char::is_whitespace)?;
        (c.to_string(), r.trim_start())
    };
    let (module, args) = match rest.split_once(char::is_whitespace) {
        Some((m, a)) => (m.to_string(), a.trim().to_string()),
        None => (rest.to_string(), String::new()),
    };
    Some((kind.to_string(), control, module, args))
}

/// Flattens the `auth` phase as Linux-PAM would evaluate it, expanding
/// `include`, `substack` and `@include` from `pam_dir`. Returns
/// `"module args"` strings in evaluation order.
fn flatten_auth(pam_dir: &Path, content: &str, depth: usize) -> Vec<String> {
    assert!(depth < 8, "include loop in fixture");
    let mut out = Vec::new();
    for line in content.lines() {
        let Some((kind, control, module, args)) = parse_rule(line) else {
            continue;
        };
        let is_auth = kind == "auth" || kind == "-auth" || kind == "@include";
        if !is_auth {
            continue;
        }
        if kind == "@include" || control == "include" || control == "substack" {
            if let Ok(sub) = fs::read_to_string(pam_dir.join(&module)) {
                out.extend(flatten_auth(pam_dir, &sub, depth + 1));
            }
            continue;
        }
        out.push(format!("{module} {args}").trim().to_string());
    }
    out
}

fn first_index(stack: &[String], needle: &str) -> Option<usize> {
    stack.iter().position(|m| m.contains(needle))
}

fn line_index(content: &str, needle: &str) -> usize {
    content
        .lines()
        .position(|l| l.contains(needle))
        .unwrap_or_else(|| panic!("line containing {needle:?} not found in:\n{content}"))
}

/// Asserts that, in the flattened auth stack, `pam_soos.so` runs after every
/// listed gate and before the first credential module.
fn assert_soos_after_gates(f: &Fixture, gates: &[&str], credential: &str) {
    let content = fs::read_to_string(&f.pam_file).unwrap();
    let stack = flatten_auth(&f.pam_dir, &content, 0);
    let soos = first_index(&stack, "pam_soos.so").expect("pam_soos.so in the auth stack");
    for gate in gates {
        let gate_at = first_index(&stack, gate)
            .unwrap_or_else(|| panic!("gate {gate:?} missing from stack {stack:#?}"));
        assert!(
            gate_at < soos,
            "{gate:?} (#{gate_at}) must run before pam_soos.so (#{soos}): {stack:#?}"
        );
    }
    let cred = first_index(&stack, credential).expect("credential module in stack");
    assert!(
        soos < cred,
        "pam_soos.so (#{soos}) must run before {credential:?} (#{cred}): {stack:#?}"
    );
}

