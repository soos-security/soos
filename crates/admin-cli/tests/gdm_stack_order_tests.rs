#[test]
fn test_gdm_enable_fedora_never_inserts_at_top_and_guards_faillock_preauth() {
    let f = fixture(
        FEDORA_GDM_PASSWORD,
        &[
            ("password-auth", FEDORA_PASSWORD_AUTH),
            ("postlogin", FEDORA_POSTLOGIN),
        ],
    );
    let content = enable(&f);

    let first = content.lines().next().unwrap();
    assert!(
        first.contains("pam_selinux_permit.so"),
        "the first rule stays first (pam_soos.so is never inserted at index 0): {first}"
    );
    let soos = line_index(&content, "pam_soos.so");
    assert!(line_index(&content, "pam_selinux_permit.so") < soos);
    assert!(soos < line_index(&content, "substack      password-auth"));
    assert_eq!(
        content
            .lines()
            .nth(line_index(&content, "pam_faillock.so"))
            .unwrap(),
        "auth  required  pam_faillock.so preauth silent"
    );
    assert_soos_after_gates(
        &f,
        &["pam_selinux_permit.so", "pam_faillock.so preauth"],
        "pam_unix.so",
    );
    // The account phase (pam_nologin, pam_faillock account) is untouched.
    assert!(content.contains("account     required      pam_nologin.so\n"));
}

