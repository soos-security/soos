#[test]
fn test_gdm_enable_ubuntu_inserts_after_nologin_and_succeed_if_before_common_auth() {
    let f = fixture(UBUNTU_GDM_PASSWORD, &[("common-auth", UBUNTU_COMMON_AUTH)]);
    let content = enable(&f);

    let soos = line_index(&content, "pam_soos.so");
    assert!(line_index(&content, "pam_nologin.so") < soos);
    assert!(line_index(&content, "pam_succeed_if.so") < soos);
    assert_eq!(
        soos + 2,
        line_index(&content, "@include common-auth"),
        "the managed block ends right before '@include common-auth'"
    );
    assert_eq!(
        content.lines().nth(soos).unwrap(),
        GDM_PAM_LINE,
        "the inserted rule is exactly GDM_PAM_LINE"
    );
    assert!(
        !content.contains("pam_faillock.so"),
        "no faillock guard when the delegated stack has no faillock"
    );
    assert_soos_after_gates(&f, &["pam_nologin.so", "pam_succeed_if.so"], "pam_unix.so");

    // Every original line is preserved verbatim and in order.
    let without_block: Vec<&str> = content
        .lines()
        .filter(|l| *l != GDM_BLOCK_BEGIN && *l != GDM_BLOCK_END && *l != GDM_PAM_LINE)
        .collect();
    assert_eq!(
        without_block,
        UBUNTU_GDM_PASSWORD.lines().collect::<Vec<_>>()
    );
}

#[test]
fn test_gdm_enable_ubuntu_faillock_profile_adds_preauth_guard_before_soos() {
    let f = fixture(
        UBUNTU_GDM_PASSWORD,
        &[("common-auth", UBUNTU_COMMON_AUTH_FAILLOCK)],
    );
    let content = enable(&f);

    let soos = line_index(&content, "pam_soos.so");
    let guard = line_index(&content, "pam_faillock.so preauth");
    assert!(
        guard < soos,
        "faillock preauth guard must precede pam_soos.so:\n{content}"
    );
    assert!(line_index(&content, GDM_BLOCK_BEGIN) < guard);
    assert!(soos < line_index(&content, "@include common-auth"));
    assert_eq!(
        content.lines().nth(guard).unwrap(),
        "auth  requisite  pam_faillock.so preauth",
        "the guard copies the control and arguments of the delegated preauth rule"
    );
    assert_soos_after_gates(
        &f,
        &[
            "pam_nologin.so",
            "pam_succeed_if.so",
            "pam_faillock.so preauth",
        ],
        "pam_unix.so",
    );
}

