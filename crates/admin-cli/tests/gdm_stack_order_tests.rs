/// End to end through the `soos-admin` binary: `gdm enable` refuses to edit the PAM
/// file while `pam_soos.so` is not installed, and succeeds once it is.
#[test]
fn test_soos_admin_gdm_enable_refuses_when_module_is_not_installed() {
    let f = fixture(UBUNTU_GDM_PASSWORD, &[("common-auth", UBUNTU_COMMON_AUTH)]);
    let modules = f.pam_dir.parent().unwrap().join("security");
    fs::create_dir(&modules).unwrap();
    let run = || {
        std::process::Command::new(env!("CARGO_BIN_EXE_soos-admin"))
            .args(["gdm", "enable", "--pam-file"])
            .arg(&f.pam_file)
            .arg("--disable-file")
            .arg(&f.disable_file)
            .arg("--pam-module-dir")
            .arg(&modules)
            .output()
            .unwrap()
    };

    let refused = run();
    assert!(!refused.status.success(), "missing module must be refused");
    assert!(String::from_utf8_lossy(&refused.stderr).contains("pam_soos.so not found"));
    assert_eq!(
        fs::read_to_string(&f.pam_file).unwrap(),
        UBUNTU_GDM_PASSWORD
    );
    assert!(!pam_backup_path(&f.pam_file).exists());

    fs::write(modules.join(PAM_MODULE_FILE), b"\x7fELF").unwrap();
    let accepted = run();
    assert!(
        accepted.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&accepted.stderr)
    );
    assert!(fs::read_to_string(&f.pam_file)
        .unwrap()
        .contains(GDM_PAM_LINE));
}

