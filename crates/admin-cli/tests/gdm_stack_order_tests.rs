#[test]
fn test_gdm_enable_arch_guards_shells_nologin_and_faillock_from_nested_includes() {
    let f = fixture(
        ARCH_GDM_PASSWORD,
        &[
            ("system-local-login", ARCH_SYSTEM_LOCAL_LOGIN),
            ("system-login", ARCH_SYSTEM_LOGIN),
            ("system-auth", ARCH_SYSTEM_AUTH),
        ],
    );
    let content = enable(&f);

    let soos = line_index(&content, "pam_soos.so");
    let shells = line_index(&content, "pam_shells.so");
    let nologin = line_index(&content, "pam_nologin.so");
    let faillock = line_index(&content, "pam_faillock.so preauth");
    assert!(
        shells < nologin && nologin < faillock && faillock < soos,
        "guards keep the original evaluation order before pam_soos.so:\n{content}"
    );
    assert!(
        soos < line_index(
            &content,
            "auth       include                     system-local-login"
        )
    );
    assert_soos_after_gates(
        &f,
        &["pam_shells.so", "pam_nologin.so", "pam_faillock.so preauth"],
        "pam_unix.so",
    );
    // Rules after the first credential module (authfail, authsucc) are never copied.
    assert!(!content.contains("authfail"));
    assert!(!content.contains("authsucc"));
}

