/// RAN-S5 (RAN5, spec §2.3): the four assets are embedded as `image/png` and routed by their
/// exact paths; the CSP literal is byte-identical to the pinned one.
#[test]
fn test_ran_s5_android_assets_are_embedded_and_routed() {
    let assets = strip_comments(production_part(&read(ASSETS_RS)));
    let enum_body = {
        let at = assets.find("pub enum AssetId").expect("pub enum AssetId");
        let open = at + assets[at..].find('{').expect("{");
        let close = open + assets[open..].find('}').expect("}");
        assets[open + 1..close].to_string()
    };
    for (variant, file) in NEW_ASSETS {
        assert!(
            enum_body.contains(&format!("{variant},")),
            "AssetId has the variant {variant}"
        );
        let arm_head = format!("AssetId::{variant} =>");
        let at = assets
            .find(&arm_head)
            .unwrap_or_else(|| panic!("asset() has the arm {arm_head}"));
        let arm = &assets[at + arm_head.len()..];
        let arm = &arm[..arm.find("AssetId::").unwrap_or(arm.len())];
        assert!(
            arm.contains("content_type: \"image/png\""),
            "{variant} is image/png: {arm}"
        );
        assert!(
            arm.contains(&format!("include_bytes!(\"../assets/{file}\")")),
            "{variant} embeds {file}: {arm}"
        );
    }
    let routes = strip_comments(production_part(&read(ROUTES_RS)));
    let route_body = {
        let at = routes.find("pub fn route(").expect("pub fn route(");
        let open = at + routes[at..].find('{').expect("{");
        let mut depth = 0usize;
        let mut end = open;
        for (i, c) in routes[open..].char_indices() {
            match c {
                '{' => depth += 1,
                '}' => {
                    depth -= 1;
                    if depth == 0 {
                        end = open + i;
                        break;
                    }
                }
                _ => {}
            }
        }
        routes[open..end].to_string()
    };
    for (variant, file) in NEW_ASSETS {
        let arm = format!("\"/{file}\" => Some(Route::Asset(AssetId::{variant})),");
        assert!(
            route_body.contains(&arm),
            "route() maps the read route {arm}"
        );
    }
    let http = read(HTTP_RS);
    let served = csp_of_rust_literal(&http, "Content-Security-Policy: ");
    assert_eq!(served, PINNED_CSP, "http.rs CSP unchanged");
    let pinned = csp_of_rust_literal(&read(HTTP_TESTS), "const CSP: &str = \"");
    assert_eq!(
        served, pinned,
        "http.rs CSP equals the pinned http_tests.rs CSP"
    );
    for forbidden in ["worker-src", "blob:", "data:"] {
        assert!(
            !served.contains(forbidden),
            "CSP must not contain {forbidden}"
        );
    }
}

