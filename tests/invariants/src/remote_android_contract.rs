fn read_bytes(rel: &str) -> Vec<u8> {
    let path = workspace_root().join(rel);
    fs::read(&path).unwrap_or_else(|e| panic!("Cannot read {}: {e}", path.display()))
}

/// `text` without any whitespace.
fn no_whitespace(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}

/// Whitespace runs collapsed to one space.
fn squash(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Whether a `/` at byte `i` of `code` starts a regular expression literal (and not a
/// division): the previous non-blank byte is an operator, an opening bracket or nothing.
fn starts_regex(code: &[u8], i: usize) -> bool {
    let mut j = i;
    while j > 0 {
        j -= 1;
        let b = code[j];
        if b == b' ' || b == b'\t' || b == b'\n' || b == b'\r' {
            continue;
        }
        if b.is_ascii_alphanumeric() || b == b'_' || b == b'$' {
            let mut k = j + 1;
            while k > 0
                && (code[k - 1].is_ascii_alphanumeric()
                    || code[k - 1] == b'_'
                    || code[k - 1] == b'$')
            {
                k -= 1;
            }
            let word = &code[k..=j];
            return [
                &b"return"[..],
                b"typeof",
                b"case",
                b"in",
                b"of",
                b"void",
                b"delete",
                b"throw",
                b"yield",
                b"await",
            ]
            .contains(&word);
        }
        return matches!(
            b,
            b'(' | b','
                | b'='
                | b':'
                | b'['
                | b'!'
                | b'&'
                | b'|'
                | b'?'
                | b'{'
                | b'}'
                | b';'
                | b'+'
                | b'-'
                | b'*'
                | b'%'
                | b'<'
                | b'>'
                | b'~'
                | b'^'
        );
    }
    true
}

/// End (exclusive) of the string, template or regex literal starting at `i`.
fn literal_end(code: &[u8], i: usize) -> usize {
    let quote = code[i];
    let mut j = i + 1;
    let mut in_class = false;
    while j < code.len() {
        let b = code[j];
        if b == b'\\' {
            j += 2;
            continue;
        }
        if quote == b'/' {
            if b == b'[' {
                in_class = true;
            } else if b == b']' {
                in_class = false;
            } else if b == b'/' && !in_class {
                return j + 1;
            } else if b == b'\n' {
                return j;
            }
        } else if b == quote {
            return j + 1;
        }
        j += 1;
    }
    code.len()
}

/// JavaScript source with `//` and `/* */` comments removed; strings, template literals and
/// regular expression literals are kept verbatim.
fn strip_js_comments(src: &str) -> String {
    let code = src.as_bytes();
    let mut out: Vec<u8> = Vec::with_capacity(code.len());
    let mut i = 0;
    while i < code.len() {
        let b = code[i];
        if b == b'"' || b == b'\'' || b == b'`' {
            let end = literal_end(code, i);
            out.extend_from_slice(&code[i..end]);
            i = end;
            continue;
        }
        if b == b'/' && i + 1 < code.len() && code[i + 1] == b'/' {
            while i < code.len() && code[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if b == b'/' && i + 1 < code.len() && code[i + 1] == b'*' {
            i += 2;
            while i + 1 < code.len() && !(code[i] == b'*' && code[i + 1] == b'/') {
                i += 1;
            }
            i += 2;
            continue;
        }
        if b == b'/' && starts_regex(&out, out.len()) {
            let end = literal_end(code, i);
            out.extend_from_slice(&code[i..end]);
            i = end;
            continue;
        }
        out.push(b);
        i += 1;
    }
    String::from_utf8(out).expect("UTF-8 source")
}

/// The comment-free code of a JavaScript asset.
fn js(rel: &str) -> String {
    assert!(exists(rel), "{rel} must exist");
    strip_js_comments(&read(rel))
}

/// The body (between the first `{` at or after `at` and its matching `}`) of comment-free
/// JavaScript `code`, braces inside literals ignored.
fn js_block_from(code: &str, at: usize) -> String {
    let bytes = code.as_bytes();
    let open = at
        + code[at..]
            .find('{')
            .unwrap_or_else(|| panic!("no block after byte {at}"));
    let mut depth = 0usize;
    let mut i = open;
    while i < bytes.len() {
        let b = bytes[i];
        if b == b'"' || b == b'\'' || b == b'`' || (b == b'/' && starts_regex(bytes, i)) {
            i = literal_end(bytes, i);
            continue;
        }
        if b == b'{' {
            depth += 1;
        } else if b == b'}' {
            depth -= 1;
            if depth == 0 {
                return code[open + 1..i].to_string();
            }
        }
        i += 1;
    }
    panic!("unbalanced block after byte {at}");
}

/// The body of the JavaScript function or listener whose text starts with `signature`.
fn js_body_of(code: &str, signature: &str) -> String {
    let at = code
        .find(signature)
        .unwrap_or_else(|| panic!("{signature} not found"));
    js_block_from(code, at)
}

/// Occurrences of the call `name(` not preceded by an identifier byte (`self.fetch(` counts).
fn call_count(code: &str, name: &str) -> usize {
    let needle = format!("{name}(");
    code.match_indices(&needle)
        .filter(|(at, _)| {
            *at == 0 || {
                let b = code.as_bytes()[*at - 1];
                !(b.is_ascii_alphanumeric() || b == b'_' || b == b'$')
            }
        })
        .count()
}

/// The value of the JavaScript string constant `const NAME = "value";`.
fn js_const_string(code: &str, name: &str) -> String {
    let prefix = format!("const {name} = \"");
    let at = code
        .find(&prefix)
        .unwrap_or_else(|| panic!("const {name} = \"…\"; not found"));
    let rest = &code[at + prefix.len()..];
    let end = rest.find('"').expect("closing quote");
    rest[..end].to_string()
}

/// The value of the Rust string constant `pub const NAME: &str = "value";`.
fn rust_const_string(code: &str, name: &str) -> String {
    let prefix = format!("pub const {name}: &str = \"");
    let at = code
        .find(&prefix)
        .unwrap_or_else(|| panic!("pub const {name}: &str = \"…\"; not found"));
    let rest = &code[at + prefix.len()..];
    let end = rest.find('"').expect("closing quote");
    rest[..end].to_string()
}

/// The text of the `## <number>.` section of a Markdown document (up to the next `## `,
/// without the final line break).
fn section<'a>(doc: &'a str, number: &str) -> &'a str {
    let heading = format!("\n## {number} ");
    let at = doc
        .find(&heading)
        .unwrap_or_else(|| panic!("section ## {number} not found"));
    let rest = &doc[at + 1..];
    let end = rest[3..].find("\n## ").map_or(rest.len(), |e| e + 3);
    &rest[..end]
}

/// Every `Face ID` of `text` is immediately followed by `, fingerprint or screen lock`.
fn face_id_offenders(text: &str) -> Vec<String> {
    text.match_indices("Face ID")
        .filter(|(at, _)| !text[at + "Face ID".len()..].starts_with(NEUTRAL_SUFFIX))
        .map(|(at, _)| {
            let end = (at + 60).min(text.len());
            let end = (end..=text.len())
                .find(|e| text.is_char_boundary(*e))
                .unwrap_or(text.len());
            text[at..end].replace('\n', " ")
        })
        .collect()
}

/// JSON text with the whitespace outside strings removed.
fn compact_json(text: &str) -> String {
    let mut out = String::new();
    let mut in_str = false;
    let mut escaped = false;
    for ch in text.chars() {
        if in_str {
            out.push(ch);
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == '"' {
                in_str = false;
            }
        } else if ch == '"' {
            in_str = true;
            out.push(ch);
        } else if !ch.is_whitespace() {
            out.push(ch);
        }
    }
    out
}

/// PNG structure: IHDR fields and the ordered chunk names.
#[derive(Debug)]
struct PngInfo {
    width: u32,
    height: u32,
    depth: u8,
    color_type: u8,
    interlace: u8,
    chunks: Vec<String>,
}

fn be32(b: &[u8]) -> u32 {
    u32::from_be_bytes([b[0], b[1], b[2], b[3]])
}

fn png_info(bytes: &[u8]) -> Result<PngInfo, String> {
    const MAGIC: [u8; 8] = [0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A];
    if bytes.len() < 8 || bytes[..8] != MAGIC {
        return Err("not a PNG (signature)".to_string());
    }
    let mut chunks = Vec::new();
    let mut header: Option<(u32, u32, u8, u8, u8)> = None;
    let mut i = 8usize;
    while i < bytes.len() {
        if i + 12 > bytes.len() {
            return Err(format!("truncated chunk header at {i}"));
        }
        let len = be32(&bytes[i..i + 4]) as usize;
        let kind = String::from_utf8_lossy(&bytes[i + 4..i + 8]).to_string();
        let data_end = i + 8 + len;
        if data_end + 4 > bytes.len() {
            return Err(format!("truncated chunk {kind}"));
        }
        if kind == "IHDR" {
            if len != 13 {
                return Err("IHDR length is not 13".to_string());
            }
            let d = &bytes[i + 8..data_end];
            header = Some((be32(&d[0..4]), be32(&d[4..8]), d[8], d[9], d[12]));
        }
        chunks.push(kind);
        i = data_end + 4;
    }
    let (width, height, depth, color_type, interlace) =
        header.ok_or_else(|| "no IHDR chunk".to_string())?;
    Ok(PngInfo {
        width,
        height,
        depth,
        color_type,
        interlace,
        chunks,
    })
}

/// The CSP value of a Rust source holding `Content-Security-Policy: …\r\n` or a `CSP`
/// constant, with `\`-newline continuations and their indentation removed.
fn csp_of_rust_literal(src: &str, start_marker: &str) -> String {
    let at = src
        .find(start_marker)
        .unwrap_or_else(|| panic!("{start_marker} not found"));
    let rest = &src[at + start_marker.len()..];
    let end = ["\\r\\n", "\";"]
        .iter()
        .filter_map(|m| rest.find(m))
        .min()
        .expect("end of the CSP literal");
    let raw = &rest[..end];
    let mut out = String::new();
    let mut lines = raw.split("\\\n");
    if let Some(first) = lines.next() {
        out.push_str(first);
    }
    for line in lines {
        out.push_str(line.trim_start());
    }
    out
}

/// Self-test of the JavaScript helpers on literal snippets.
#[test]
fn test_ran_helper_js_lexer_self_test() {
    let src = "const A = \"// not a comment\"; // gone\nconst R = /\\//g; /* gone */ const B = `{`;\nfunction f(x) { if (x) { return \"}\"; } return /}/.test(x); }\n";
    let code = strip_js_comments(src);
    assert!(code.contains("\"// not a comment\""), "{code}");
    assert!(!code.contains("gone"), "{code}");
    assert!(code.contains("/\\//g"), "{code}");
    assert!(code.contains("`{`"), "{code}");
    let body = js_body_of(&code, "function f(");
    assert!(body.contains("return \"}\";"), "{body}");
    assert!(body.trim_end().ends_with("return /}/.test(x);"), "{body}");
    assert_eq!(call_count("a.fetch(x); fetch(y); prefetch(z)", "fetch"), 2);
    assert_eq!(js_const_string("const P = \"/x\";", "P"), "/x");
    assert_eq!(
        face_id_offenders("Face ID, fingerprint or screen lock and Face ID alone").len(),
        1
    );
    let doc = "intro\n## 2g. G\ng text\n## 2h. H\nh text\n## 3. Next\n";
    assert_eq!(section(doc, "2h."), "## 2h. H\nh text");
    assert_eq!(
        csp_of_rust_literal(
            "const CSP: &str = \"default-src 'self'; \\\n                   img-src 'self'\";",
            "const CSP: &str = \""
        ),
        "default-src 'self'; img-src 'self'"
    );
}

